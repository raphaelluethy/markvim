local render = require('markvim.render')
local state = require('markvim.state')

describe('live mode', function()
  it('keeps the cursor row raw and restores it when leaving', function()
    local buf = H.buffer({ '# One', '# Two', '# Three' }, { mode = 'live' })
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
    render.cursor(buf)
    eq(0, H.count(buf, 0), 'cursor row has no marks')
    ok(H.count(buf, 1) > 0, 'other rows rendered')
    ok(H.has(buf, 0, { line_hl = 'MarkvimH1Bg' }, true), 'background stays on cursor row')
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    render.cursor(buf)
    ok(H.count(buf, 0) > 0, 'old row restored')
    eq(0, H.count(buf, 1), 'new cursor row raw')
    H.cleanup()
  end)
  it('does not restore stale marks after an edit until re-rendered', function()
    local buf = H.buffer({ '# One', 'text', '# Three' }, { mode = 'live' })
    vim.api.nvim_win_set_cursor(0, { 1, 0 })
    render.cursor(buf)
    vim.api.nvim_buf_set_lines(buf, 1, 1, false, { 'inserted' }) -- shifts rows
    vim.api.nvim_win_set_cursor(0, { 2, 0 })
    render.cursor(buf)
    eq(0, H.count(buf, 0), 'no restore with stale cache')
    render.render(buf, true)
    ok(H.count(buf, 0) > 0, 'rendered again after refresh')
    H.cleanup()
  end)
  it('sets conceal window options and restores them on detach', function()
    local win = vim.api.nvim_get_current_win()
    vim.wo[win].conceallevel = 0
    local buf = H.buffer({ '# x' }, { mode = 'live' })
    eq(3, vim.wo[win].conceallevel)
    eq('', vim.wo[win].concealcursor)
    render.set_mode(buf, 'preview')
    eq('nvic', vim.wo[win].concealcursor)
    render.detach(buf)
    eq(0, vim.wo[win].conceallevel)
    H.cleanup()
  end)
end)

describe('inline rendering', function()
  it('reuses inline trees for the same viewport but refreshes after edits or scrolling', function()
    local api = vim.api
    local buf = api.nvim_create_buf(false, true)
    local lines = { '**bold**' }
    for i = 2, 60 do
      lines[i] = ''
    end
    lines[61] = '*italic*'
    api.nvim_buf_set_lines(buf, 0, -1, false, lines)
    -- Exercise the renderer alone, with no highlighter to parse injections.
    local compute = require('markvim.compute')
    local cfg = require('markvim.config').get()
    local s = state.new(buf)
    local first, last = { { 0, 3 } }, { { 58, 60 } }
    ok(compute(buf, s, cfg, first, 80).main[0], 'renders inline markup without the highlighter')
    eq({}, s.parser:children(), 'renderer only parses the shared block tree')
    local regions = s.inline:included_regions()
    ok(compute(buf, s, cfg, { { 0, 3 } }, 60).main[0], 'inline markup still rendered after a width change')
    ok(regions == s.inline:included_regions(), 'included regions not rebuilt')
    local scrolled = compute(buf, s, cfg, last, 60)
    ok(scrolled.main[60] and not scrolled.main[0], 'new viewport rendered')
    -- Keep the byte range identical: only changedtick signals the edit.
    api.nvim_buf_set_lines(buf, 60, 61, false, { 'plain!!!' })
    eq(nil, compute(buf, s, cfg, last, 60).main[60], 'no stale emphasis after an edit')
    H.cleanup()
    api.nvim_buf_delete(buf, { force = true })
  end)
end)

describe('split mode', function()
  it('opens a scoped preview window on the same buffer', function()
    local buf = H.buffer({ '# Title', '- item', '```lua', 'x', '```' }, { mode = 'live' })
    local src_win = vim.api.nvim_get_current_win()
    render.set_mode(buf, 'split')
    local s = state.get(buf)
    ok(s.split and vim.api.nvim_win_is_valid(s.split.win), 'split window exists')
    eq(buf, vim.api.nvim_win_get_buf(s.split.win), 'same buffer')
    eq(src_win, vim.api.nvim_get_current_win(), 'focus stays in the source window')
    local view = s.views[1]
    eq({ s.split.win }, vim.api.nvim__ns_get(view.ns).wins, 'namespace scoped to the split')
    ok(#vim.api.nvim_buf_get_extmarks(buf, view.ns, 0, -1, {}) > 0, 'preview marks exist')
    local main = vim.api.nvim_create_namespace(('markvim:%d:main'):format(buf))
    eq(0, #vim.api.nvim_buf_get_extmarks(buf, main, 0, -1, {}), 'no marks in the raw edit view')
    eq('nvic', vim.wo[s.split.win].concealcursor)
    vim.api.nvim_win_close(s.split.win, true)
    vim.wait(200, function()
      return state.get(buf).mode == 'live'
    end)
    eq('live', state.get(buf).mode, 'back to live after closing the split')
    eq({}, vim.api.nvim__ns_get(view.ns).wins, 'namespace un-scoped')
    H.cleanup()
  end)
end)

describe('floating windows', function()
  it('attaches to LSP hover floats in preview mode', function()
    local lines = { '```lua', 'local x = 1', '```', '', '# Heading', 'Some **doc** text with `code`.' }
    local fbuf, fwin = vim.lsp.util.open_floating_preview(lines, 'markdown', { border = 'single' })
    local s = state.get(fbuf)
    ok(s, 'attached to the float buffer')
    eq('preview', s.mode)
    ok(s.float)
    ok(H.has(fbuf, 4, { col = 0, end_col = 2, conceal = '' }), 'heading rendered')
    ok(not H.has(fbuf, 1, { line_hl = 'MarkvimCode' }, true), 'no code bg in floats')
    eq('nvic', vim.wo[fwin].concealcursor)
    -- fence lines are hidden, so the float should not be taller than the visible lines
    ok(
      vim.api.nvim_win_get_height(fwin) <= 4,
      'height accounts for hidden fences: ' .. vim.api.nvim_win_get_height(fwin)
    )
    vim.api.nvim_win_close(fwin, true)
    vim.wait(100, function()
      return state.get(fbuf) == nil
    end)
    eq(nil, state.get(fbuf), 'detached after the float closed')
    H.cleanup()
  end)
end)

describe('render_lines API', function()
  it('renders arbitrary markdown into a scratch buffer', function()
    local buf = require('markvim').render_lines({ '# Hi', '- a' })
    ok(state.get(buf), 'attached')
    eq('preview', state.get(buf).mode)
    vim.api.nvim_set_current_buf(buf)
    render.render(buf, true)
    ok(H.has(buf, 0, { conceal = '' }))
    H.cleanup()
  end)
end)
