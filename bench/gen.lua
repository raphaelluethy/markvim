-- Generate a large, varied markdown file: nvim --headless --clean -l bench/gen.lua <out> [sections]
local out, n = arg[1], tonumber(arg[2]) or 500
local lines = {}
local function add(s)
  lines[#lines + 1] = s
end
for i = 1, n do
  add(('# Section %d'):format(i))
  add('')
  add(('Paragraph with **bold**, *italic*, `code`, ~~strike~~ and a [link](https://example.com/%d).'):format(i))
  add(('Another line with <https://autolink.example> and ![image](img%d.png) and [[wiki|alias]].'):format(i))
  add('')
  add('## Lists')
  add('- item one with `inline code`')
  add('  - nested item')
  add('    - deeper [ref][1]')
  add('- [ ] task open')
  add('- [x] task done')
  add('1. ordered one')
  add('2. ordered two')
  add('')
  add('> [!NOTE] Something to note')
  add('> quoted text continues here')
  add('> > nested quote')
  add('')
  add('| Column A | Column B | C |')
  add('|:---------|:--------:|--:|')
  add(('| value %d | **bold** | 1 |'):format(i))
  add('| longer value | x | 22 |')
  add('')
  add('```lua')
  add('local function f(x)')
  add('  return x * 2')
  add('end')
  add('```')
  add('')
  add('---')
  add('')
  add('### Sub heading')
  add('<!-- a comment -->')
  add('Text $x^2$ and \\* escaped.')
  add('')
end
vim.fn.writefile(lines, out)
io.write(('wrote %d lines to %s\n'):format(#lines, out))
vim.cmd('qa!')
